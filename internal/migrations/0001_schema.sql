-- 0001: temel şema
-- Kimlikler bigint identity: keyset sayfalama için sıralı ve dizinli.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE user_role      AS ENUM ('donor','nurse','lab','bank','hospital','admin');
CREATE TYPE abo_group      AS ENUM ('O','A','B','AB');
CREATE TYPE sex_t          AS ENUM ('M','F');
CREATE TYPE donation_type  AS ENUM ('whole_blood','platelet_apheresis');
CREATE TYPE component_t    AS ENUM ('RBC','PLT','FFP');
CREATE TYPE product_status AS ENUM ('pending_test','available','reserved','issued','transfused',
                                    'quarantined','discarded','expired','split');
CREATE TYPE urgency_t      AS ENUM ('routine','urgent','emergency');

CREATE TABLE hospitals (
    id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE,
    city  text NOT NULL
);

CREATE TABLE donors (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_no          text NOT NULL UNIQUE,
    first_name        text NOT NULL CHECK (length(first_name) BETWEEN 1 AND 80),
    last_name         text NOT NULL CHECK (length(last_name) BETWEEN 1 AND 80),
    sex               sex_t NOT NULL,
    birth_date        date NOT NULL CHECK (birth_date > DATE '1900-01-01'),
    abo               abo_group NOT NULL,
    rh_positive       boolean NOT NULL,
    phone             text,
    email             text,
    -- Sağlık beyanı (ilaçlar, hastalıklar, seyahatler) AES-256-GCM ile şifreli.
    health_enc        bytea NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX donors_group_idx ON donors (abo, rh_positive);
CREATE INDEX donors_name_idx  ON donors (lower(last_name), lower(first_name));

CREATE TABLE users (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email         text NOT NULL UNIQUE CHECK (email = lower(email) AND position('@' in email) > 1),
    password_hash text NOT NULL,
    role          user_role NOT NULL,
    full_name     text NOT NULL,
    hospital_id   bigint REFERENCES hospitals(id),
    donor_id      bigint UNIQUE REFERENCES donors(id),
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (role <> 'hospital' OR hospital_id IS NOT NULL),
    CHECK (role <> 'donor'    OR donor_id    IS NOT NULL)
);

CREATE TABLE refresh_tokens (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id),
    token_hash  bytea NOT NULL UNIQUE,
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz
);

-- Zaman geçerlilikli kurallar. Aynı kod için geçerlilik aralıkları çakışamaz.
CREATE TABLE rule_versions (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        text NOT NULL CHECK (code IN ('eligibility','shelf_life')),
    params      jsonb NOT NULL,
    valid_from  date NOT NULL,
    valid_to    date,
    note        text,
    created_by  bigint REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    EXCLUDE USING gist (code WITH =, daterange(valid_from, valid_to, '[)') WITH &&)
);

CREATE TABLE deferrals (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    donor_id    bigint NOT NULL REFERENCES donors(id),
    reason_code text NOT NULL,
    starts_on   date NOT NULL,
    ends_on     date,              -- NULL = kalıcı red
    note        text,
    created_by  bigint REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_on IS NULL OR ends_on > starts_on)
);
CREATE INDEX deferrals_donor_idx ON deferrals (donor_id);

CREATE TABLE appointments (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    donor_id       bigint NOT NULL REFERENCES donors(id),
    scheduled_at   timestamptz NOT NULL,
    donation_type  donation_type NOT NULL DEFAULT 'whole_blood',
    status         text NOT NULL DEFAULT 'booked'
                   CHECK (status IN ('booked','completed','cancelled','no_show')),
    created_at     timestamptz NOT NULL DEFAULT now()
);
-- Bir bağışçının aynı anda en fazla bir açık randevusu olabilir.
CREATE UNIQUE INDEX appointments_one_open ON appointments (donor_id) WHERE status = 'booked';
CREATE INDEX appointments_day_idx ON appointments (scheduled_at);

CREATE TABLE donations (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id       bigint NOT NULL REFERENCES donors(id),
    appointment_id bigint UNIQUE REFERENCES appointments(id),
    donation_type  donation_type NOT NULL,
    collected_at   timestamptz NOT NULL,
    volume_ml      integer NOT NULL CHECK (volume_ml BETWEEN 150 AND 700),
    hemoglobin     numeric(4,1) NOT NULL CHECK (hemoglobin BETWEEN 5 AND 25),
    weight_kg      numeric(5,1) NOT NULL CHECK (weight_kg BETWEEN 30 AND 250),
    bag_no         text NOT NULL UNIQUE,
    nurse_id       bigint REFERENCES users(id),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX donations_donor_idx ON donations (donor_id, collected_at DESC);

CREATE TABLE test_results (
    donation_id  bigint PRIMARY KEY REFERENCES donations(id),
    hiv          boolean NOT NULL,
    hbv          boolean NOT NULL,
    hcv          boolean NOT NULL,
    syphilis     boolean NOT NULL,
    outcome      text NOT NULL CHECK (outcome IN ('negative','positive')),
    entered_by   bigint REFERENCES users(id),
    entered_at   timestamptz NOT NULL DEFAULT now(),
    version      integer NOT NULL DEFAULT 1,
    CHECK ((outcome = 'positive') = (hiv OR hbv OR hcv OR syphilis))
);
CREATE INDEX test_results_outcome_idx ON test_results (outcome);

-- Test sonucu değişikliği: iki farklı laboratuvar uzmanı gerekir.
CREATE TABLE test_change_requests (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    donation_id   bigint NOT NULL REFERENCES test_results(donation_id),
    proposed      jsonb NOT NULL,
    reason        text NOT NULL CHECK (length(reason) >= 5),
    requested_by  bigint NOT NULL REFERENCES users(id),
    requested_at  timestamptz NOT NULL DEFAULT now(),
    status        text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    decided_by    bigint REFERENCES users(id),
    decided_at    timestamptz,
    CHECK (decided_by IS NULL OR decided_by <> requested_by),
    CHECK ((status = 'pending') = (decided_by IS NULL))
);
CREATE UNIQUE INDEX test_change_one_pending ON test_change_requests (donation_id) WHERE status = 'pending';

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_no   text NOT NULL UNIQUE,
    donation_id  bigint NOT NULL REFERENCES donations(id),
    parent_id    bigint REFERENCES products(id),
    component    component_t NOT NULL,
    abo          abo_group NOT NULL,
    rh_positive  boolean NOT NULL,
    volume_ml    integer NOT NULL CHECK (volume_ml > 0),
    produced_at  timestamptz NOT NULL,
    expires_at   timestamptz NOT NULL,
    status       product_status NOT NULL DEFAULT 'pending_test',
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (expires_at > produced_at),
    CHECK (parent_id IS NULL OR parent_id <> id)
);
-- Tahsis sorgusu: uygun ürünleri gruba göre FEFO sırasıyla getirir.
CREATE INDEX products_alloc_idx ON products (component, abo, rh_positive, expires_at)
    WHERE status = 'available';
CREATE INDEX products_donation_idx ON products (donation_id);
CREATE INDEX products_parent_idx   ON products (parent_id) WHERE parent_id IS NOT NULL;
CREATE INDEX products_status_idx   ON products (status, expires_at);

-- Geçerli durum geçişleri (kural tablosu).
CREATE TABLE product_transitions (
    from_status product_status NOT NULL,
    to_status   product_status NOT NULL,
    PRIMARY KEY (from_status, to_status)
);
INSERT INTO product_transitions VALUES
 ('pending_test','available'), ('pending_test','quarantined'), ('pending_test','discarded'),
 ('pending_test','expired'),
 ('available','reserved'), ('available','quarantined'), ('available','discarded'),
 ('available','expired'), ('available','split'),
 ('reserved','available'), ('reserved','issued'), ('reserved','quarantined'), ('reserved','expired'),
 ('issued','transfused'), ('issued','quarantined'),
 ('quarantined','discarded'), ('quarantined','available');

-- Ürün durum geçişlerinin geri alınamaz kaydı.
CREATE TABLE product_events (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   bigint NOT NULL REFERENCES products(id),
    from_status  product_status,
    to_status    product_status NOT NULL,
    actor_id     bigint,
    reason       text,
    at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX product_events_product_idx ON product_events (product_id, id);
CREATE INDEX product_events_issue_idx   ON product_events (at) WHERE to_status = 'issued';

CREATE TABLE requests (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id  bigint NOT NULL REFERENCES hospitals(id),
    component    component_t NOT NULL,
    abo          abo_group NOT NULL,
    rh_positive  boolean NOT NULL,
    units        integer NOT NULL CHECK (units BETWEEN 1 AND 20),
    urgency      urgency_t NOT NULL DEFAULT 'routine',
    patient_ref  text NOT NULL CHECK (length(patient_ref) BETWEEN 3 AND 64),
    needed_by    timestamptz,
    status       text NOT NULL DEFAULT 'open'
                 CHECK (status IN ('open','partial','reserved','issued','cancelled')),
    -- Rezervasyonu süresi dolan talep otomatik kuyruğa geri girmez; sorumlu yeniden tahsis eder.
    auto_allocate boolean NOT NULL DEFAULT true,
    created_by   bigint REFERENCES users(id),
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX requests_queue_idx    ON requests (urgency DESC, created_at) WHERE status IN ('open','partial');
CREATE INDEX requests_hospital_idx ON requests (hospital_id, id DESC);

CREATE TABLE reservations (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   bigint NOT NULL REFERENCES requests(id),
    product_id   bigint NOT NULL REFERENCES products(id),
    status       text NOT NULL DEFAULT 'active'
                 CHECK (status IN ('active','released','issued','preempted')),
    reserved_at  timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL,
    closed_at    timestamptz,
    CHECK (expires_at > reserved_at)
);
-- Son savunma hattı: bir ürün aynı anda yalnızca bir aktif rezervasyonda olabilir.
CREATE UNIQUE INDEX reservations_one_active ON reservations (product_id) WHERE status = 'active';
CREATE INDEX reservations_expiry_idx  ON reservations (expires_at) WHERE status = 'active';
CREATE INDEX reservations_request_idx ON reservations (request_id);

CREATE TABLE distributions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   bigint NOT NULL REFERENCES requests(id),
    product_id   bigint NOT NULL UNIQUE REFERENCES products(id),
    hospital_id  bigint NOT NULL REFERENCES hospitals(id),
    issued_by    bigint REFERENCES users(id),
    issued_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX distributions_day_idx ON distributions (issued_at);

CREATE TABLE transfusions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    bigint NOT NULL UNIQUE REFERENCES products(id),
    hospital_id   bigint NOT NULL REFERENCES hospitals(id),
    patient_ref   text NOT NULL,
    transfused_at timestamptz NOT NULL DEFAULT now(),
    recorded_by   bigint REFERENCES users(id)
);
CREATE INDEX transfusions_patient_idx ON transfusions (patient_ref);

CREATE TABLE stock_alerts (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    component       component_t NOT NULL,
    abo             abo_group NOT NULL,
    rh_positive     boolean NOT NULL,
    level           text NOT NULL CHECK (level IN ('critical','low')),
    available_units integer NOT NULL,
    days_of_supply  numeric(8,2) NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    resolved_at     timestamptz
);
CREATE UNIQUE INDEX stock_alerts_one_open ON stock_alerts (component, abo, rh_positive) WHERE resolved_at IS NULL;

-- Eklemeli-yalnız denetim kaydı.
CREATE TABLE audit_log (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    actor_id    bigint,
    actor_role  text,
    action      text NOT NULL,
    entity      text NOT NULL,
    entity_id   text,
    old_value   jsonb,
    new_value   jsonb,
    reason      text,
    request_id  text
);
CREATE INDEX audit_action_idx ON audit_log (action, id DESC);
CREATE INDEX audit_entity_idx ON audit_log (entity, entity_id);

CREATE TABLE idempotency_keys (
    user_id       bigint NOT NULL,
    key           text NOT NULL CHECK (length(key) BETWEEN 8 AND 128),
    method        text NOT NULL,
    path          text NOT NULL,
    request_hash  bytea NOT NULL,
    status_code   integer,
    response      bytea,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, key)
);

CREATE TABLE sim_state (
    id          integer PRIMARY KEY CHECK (id = 1),
    seed        bigint NOT NULL,
    anchor      date NOT NULL,
    donors      integer NOT NULL,
    seeded_at   timestamptz NOT NULL DEFAULT now()
);
